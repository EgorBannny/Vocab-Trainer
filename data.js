/*
 * Наборы карточек.
 *
 * Как добавить свой набор — см. README.md (раздел «Как добавить свои слова»).
 *
 * c(ru, hint, def, en, ipa, pos, ex)
 *   ru   — русский перевод; варианты через "|" (первый — основной, показывается на карточке)
 *   hint — короткая пометка для различения значений, например "компьютерная" (можно '')
 *   def  — определение на русском
 *   en   — английское слово; варианты через "|" (в диктанте принимается любой)
 *   ipa  — транскрипция; для вариантов тоже через "|" (если одна — используется для всех)
 *   pos  — часть речи
 *   ex   — пример на английском
 *
 * Слова с одинаковым английским или русским написанием (mouse, key, window, table,
 * cloud, bug ...) связываются между собой автоматически: на обороте карточки
 * показываются «Другие значения», а в диктанте принимаются все правильные переводы.
 */
function c(ru, hint, def, en, ipa, pos, ex) {
  return { ru: ru.split('|'), hint: hint, def: def, en: en.split('|'), ipa: ipa.split('|'), pos: pos, ex: ex };
}

